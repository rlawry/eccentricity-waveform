// --- Catmull-Rom cubic Hermite interpolation ---------------------------------

function _catmullRom(p0, p1, p2, p3, t) {
  const t2 = t * t, t3 = t2 * t;
  return 0.5 * (
    (2 * p1) +
    (-p0 + p2) * t +
    (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 +
    (-p0 + 3 * p1 - 3 * p2 + p3) * t3
  );
}

// --- Shared table constants --------------------------------------------------

const _N    = _LA2010D.length;      // 2001
const _STEP = 5000;                 // years between samples
const _MAX  = (_N - 1) * _STEP;    // 10,000,000 yr = 10 Myr
const _J2000_MS  = Date.UTC(2000, 0, 1, 12, 0, 0);
const _MS_PER_JY = 365.25 * 86400e3;

// --- Generic table interpolator ---------------------------------------------

function _interpolate(table, t, warnName) {
  if (t > 5000) {
    if (typeof console !== 'undefined')
      console.warn(warnName + ': t > 5000 yr (future). No data; result is unreliable.');
    t = 5000;
  }

  if (t > 0) {
    const slope = (table[0] - table[1]) / _STEP;
    return table[0] + slope * t;
  }

  const absT = -t;
  if (absT >= _MAX) {
    if (typeof console !== 'undefined')
      console.warn(warnName + ': |t| > 10 Myr; returning boundary value.');
    return table[_N - 1];
  }

  const pos = absT / _STEP;
  const i   = Math.floor(pos);
  const f   = pos - i;

  if (f === 0) return table[i];

  const i0 = Math.max(0, i - 1);
  const i1 = i;
  const i2 = Math.min(_N - 1, i + 1);
  const i3 = Math.min(_N - 1, i + 2);

  return _catmullRom(table[i0], table[i1], table[i2], table[i3], f);
}

// --- Eccentricity ------------------------------------------------------------

/**
 * Earth orbital eccentricity from the La2010d solution.
 * @param {number} t  Julian years from J2000.0 (negative = past). Range: 0 to -10 Myr.
 * @returns {number}  Eccentricity (dimensionless), Earth range ~0.001-0.059.
 */
function earthEccentricity(t) {
  return Math.max(0, _interpolate(_LA2010D, t, 'earthEccentricity'));
}

// --- Obliquity ---------------------------------------------------------------

/**
 * Earth axial obliquity from the La2004 solution.
 * @param {number} t  Julian years from J2000.0 (negative = past). Range: 0 to -10 Myr.
 * @returns {number}  Obliquity in radians, Earth range ~0.384-0.426 rad (22-24.4 deg).
 */
function earthObliquity(t) {
  return _interpolate(_LA2004_OBL, t, 'earthObliquity');
}

// --- Precession --------------------------------------------------------------

/**
 * Earth longitude of perihelion (pibar) from the La2004 solution.
 * Stored unwrapped/continuous — Catmull-Rom interpolation applies directly.
 * @param {number} t  Julian years from J2000.0 (negative = past). Range: 0 to -10 Myr.
 * @returns {number}  pibar in radians (unwrapped). J2000.0 value ≈ 1.796 rad (102.9°).
 */
function earthLongitudePerihelion(t) {
  return _interpolate(_LA2004_PIBAR, t, 'earthLongitudePerihelion');
}

/**
 * Climatic precession index: e · sin(pibar).
 * Dimensionless, range ~ -0.065 to +0.065. Dominant period ~21-23 kyr.
 * @param {number} t  Julian years from J2000.0 (negative = past).
 * @returns {number}  e · sin(pibar).
 */
function earthPrecessionIndex(t) {
  return earthEccentricity(t) * Math.sin(earthLongitudePerihelion(t));
}

/** Longitude of perihelion (radians) from a JavaScript Date. */
function earthLongitudePerihelionFromDate(date) {
  return earthLongitudePerihelion(dateToJ2000(date));
}

/** Climatic precession index from a JavaScript Date. */
function earthPrecessionIndexFromDate(date) {
  return earthPrecessionIndex(dateToJ2000(date));
}

// ─── Axial precession (general precession in longitude ψ) ────────────────────
// Secular drift only. P = 50.439273 arcsec/yr (Berger 1978 / palinsol BER78).
// Full quasi-periodic corrections (<±500 arcsec ≈ ±0.14°) omitted.
// One full precession cycle: 2π / (50.439273 × π/648000) ≈ 25,694 yr.
// ψ(0) ≡ 0 by J2000.0 reference-epoch convention.

const _PSI_P    = 50.439273;          // arcsec yr⁻¹ (Berger 1978 secular rate)
const _AS2RAD   = Math.PI / 648000;   // arcsec → radians

/**
 * General precession in longitude ψ (axial precession angle).
 *
 * @param {number} t  Julian years from J2000.0 (negative = past).
 * @returns {number}  ψ in radians. Increases with time (retrograde precession).
 *                    ψ(0) = 0; one full cycle every ~25,694 yr.
 */
function earthAxialPrecession(t) {
  return _PSI_P * t * _AS2RAD;
}

/** Axial precession angle from a JavaScript Date. */
function earthAxialPrecessionFromDate(date) {
  return earthAxialPrecession(dateToJ2000(date));
}

// --- Time helpers ------------------------------------------------------------

/** JavaScript Date to Julian years from J2000.0 */
function dateToJ2000(date) {
  return (date.getTime() - _J2000_MS) / _MS_PER_JY;
}

/** Julian Day Number to Julian years from J2000.0 */
function jdToJ2000(jd) {
  return (jd - 2451545.0) / 365.25;
}

/** Eccentricity from a JavaScript Date. */
function earthEccentricityFromDate(date) {
  return earthEccentricity(dateToJ2000(date));
}

/** Obliquity (radians) from a JavaScript Date. */
function earthObliquityFromDate(date) {
  return earthObliquity(dateToJ2000(date));
}

