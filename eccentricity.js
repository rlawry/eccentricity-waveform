// ─── Catmull-Rom cubic Hermite interpolation ─────────────────────────────────

function _catmullRom(p0, p1, p2, p3, t) {
  const t2 = t * t, t3 = t2 * t;
  return 0.5 * (
    (2 * p1) +
    (-p0 + p2) * t +
    (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 +
    (-p0 + 3 * p1 - 3 * p2 + p3) * t3
  );
}

// ─── Core function ───────────────────────────────────────────────────────────

const _N    = _LA2010D.length;      // 2001
const _STEP = 5000;                 // years between samples
const _MAX  = (_N - 1) * _STEP;    // 10,000,000 yr = 10 Myr
const _J2000_MS  = Date.UTC(2000, 0, 1, 12, 0, 0);
const _MS_PER_JY = 365.25 * 86400e3;

/**
 * Earth's orbital eccentricity from the La2010d solution.
 *
 * @param {number} t  Julian years from J2000.0 (negative = past).
 *                    Range: 0 to −10,000,000 yr (10 Myr before J2000).
 *                    For 0 < t ≤ 5000 yr (near future), linear extrapolation
 *                    is used; accuracy degrades rapidly beyond that.
 * @returns {number}  Eccentricity (dimensionless).  Earth's range: ~0.001–0.059.
 */
function earthEccentricity(t) {
  if (t > 5000) {
    if (typeof console !== 'undefined')
      console.warn('earthEccentricity: t > 5000 yr (future). No La2010d data; result is unreliable.');
    t = 5000;
  }

  if (t > 0) {
    // Near future: linear extrapolation using slope at t = 0 (from first 2 points).
    // e[-5kyr] > e[0], so de/dt going forward is negative (eccentricity decreasing).
    const slope = (_LA2010D[0] - _LA2010D[1]) / _STEP;
    return Math.max(0, _LA2010D[0] + slope * t);
  }

  const absT = -t;
  if (absT >= _MAX) {
    if (typeof console !== 'undefined')
      console.warn('earthEccentricity: |t| > 10 Myr; returning boundary value.');
    return _LA2010D[_N - 1];
  }

  const pos = absT / _STEP;
  const i   = Math.floor(pos);
  const f   = pos - i;

  if (f === 0) return _LA2010D[i];

  // Catmull-Rom spline: use surrounding 4 points (clamped at edges)
  const i0 = Math.max(0, i - 1);
  const i1 = i;
  const i2 = Math.min(_N - 1, i + 1);
  const i3 = Math.min(_N - 1, i + 2);

  return Math.max(0, _catmullRom(_LA2010D[i0], _LA2010D[i1], _LA2010D[i2], _LA2010D[i3], f));
}

// ─── Time helpers ────────────────────────────────────────────────────────────

/** JavaScript Date → Julian years from J2000.0 */
function dateToJ2000(date) {
  return (date.getTime() - _J2000_MS) / _MS_PER_JY;
}

/** Julian Day Number → Julian years from J2000.0 */
function jdToJ2000(jd) {
  return (jd - 2451545.0) / 365.25;
}

/** Eccentricity directly from a JavaScript Date. */
function earthEccentricityFromDate(date) {
  return earthEccentricity(dateToJ2000(date));
}

